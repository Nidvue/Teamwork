def _append(docs_copy: Path, rel: str, line: str) -> None:
    path = docs_copy / rel
    path.write_text(path.read_text(encoding="utf-8") + line, encoding="utf-8")


def _strip_line(docs_copy: Path, rel: str, pattern: str) -> None:
    path = docs_copy / rel
    text = path.read_text(encoding="utf-8")
    mutated = re.sub(pattern, "", text, count=1, flags=re.M)
    assert mutated != text, f"{pattern!r} matched nothing in {rel}"
    path.write_text(mutated, encoding="utf-8")


def test_mutant_a_broken_authored_link_is_reported(docs_copy):
    _append(docs_copy, f"{TEAM_DIR}/Plan.md", "\nSee [the ghost](ghost-doc.md).\n")
    problems = link_problems(docs_copy)
    assert any("ghost-doc.md" in problem for problem in problems), problems


def test_mutant_a_link_inside_a_code_fence_is_not_reported(docs_copy):
    """The example in a fenced block is not a link the team maintains."""
    _append(docs_copy, f"{TEAM_DIR}/Plan.md", "\n```\n[example](also-ghost.md)\n```\n")
    assert link_problems(docs_copy) == []


def test_mutant_a_quoted_archive_evidence_link_is_not_reported(docs_copy):
    """`Archive.md` quotations are copied from other agents, not authored here."""
    _append(docs_copy, f"{TEAM_DIR}/Archive.md", "\n- reviewer evidence: [x](ghost-quoted.md)\n")
    assert link_problems(docs_copy) == []
    _append(docs_copy, f"{TEAM_DIR}/Archive.md", "\n[authored](ghost-authored.md)\n")
    problems = link_problems(docs_copy)
    assert any("ghost-authored.md" in problem for problem in problems), problems


def test_mutant_a_missing_owner_line_is_reported(docs_copy):
    _strip_line(docs_copy, f"{TEAM_DIR}/Risks.md", r"^Owner:.*$\n")
    problems = structure_problems(docs_copy)
    assert any("Risks.md: no `Owner:` line" in problem for problem in problems), problems


def test_mutant_a_missing_related_line_is_reported(docs_copy):
    _strip_line(docs_copy, f"{TEAM_DIR}/Costs.md", r"^Related:.*$\n")
    problems = structure_problems(docs_copy)
    assert any("Costs.md: no `Related:` line" in problem for problem in problems), problems


def test_mutant_a_second_h1_is_reported(docs_copy):
    _append(docs_copy, f"{DOCS_DIR}/index.md", "\n# Second title\n")
    problems = structure_problems(docs_copy)
    assert any("2 level-1 heading(s)" in problem for problem in problems), problems


def test_mutant_a_related_line_pushed_below_the_first_section_is_reported(docs_copy):
    """Front matter is not "anywhere in the file": a buried line is a lost line."""
    path = docs_copy / TEAM_DIR / "Risks.md"
    text = path.read_text(encoding="utf-8")
    owner = re.search(r"^Owner:.*\n", text, flags=re.M)
    assert owner
    path.write_text(
        text.replace(owner.group(0), "", 1) + "\n## Appendix\n\n" + owner.group(0), "utf-8"
    )
    problems = structure_problems(docs_copy)
    assert any("Risks.md: no `Owner:` line" in problem for problem in problems), problems


def test_mutant_a_new_document_is_covered_without_being_listed(docs_copy):
    """The walk, not a name list: an unowned new page fails the day it lands."""
    (docs_copy / DOCS_DIR / "guide" / "brand-new.md").write_text(
        "# Brand new\n\nNo owner here.\n", encoding="utf-8"
    )
    problems = structure_problems(docs_copy)
    assert any("guide/brand-new.md: no `Owner:` line" in problem for problem in problems), problems


def test_mutant_second_folded_owner_line_is_reported(docs_copy):
    """The combined form is tolerated once; a second document adopting it is not."""
    path = docs_copy / TEAM_DIR / "Costs.md"
    text = path.read_text(encoding="utf-8")
    owner = re.search(r"^Owner:.*\n", text, flags=re.M)
    related = re.search(r"^Related:.*\n", text, flags=re.M)
    assert owner and related
    folded_line = f"{owner.group(0).rstrip()}\n"
    mutated = text.replace(owner.group(0), folded_line, 1)
    mutated = mutated.replace(related.group(0), "", 1)
    mutated = mutated.replace(
        folded_line,
        folded_line.rstrip("\n") + " " + related.group(0).strip() + "\n",
        1,
    )
    path.write_text(mutated, encoding="utf-8")
    folded = [
        candidate.relative_to(docs_copy).as_posix()
        for candidate in markdown_files(docs_copy)
        if combined_preamble_lines(candidate, docs_copy)
    ]
    assert folded == [f"{TEAM_DIR}/Costs.md", f"{TEAM_DIR}/Pi-Packaging.md"], folded
