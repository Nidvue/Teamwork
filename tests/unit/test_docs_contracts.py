def test_every_document_has_one_title_an_owner_and_related_links():
    assert structure_problems(REPO_ROOT) == []


def test_every_authored_relative_link_resolves():
    assert link_problems(REPO_ROOT) == []


def test_the_generated_manifest_is_the_only_document_without_an_owner():
    """The exemption is earned: the engine writes that file, nothing else."""
    without_owner = [
        path.relative_to(REPO_ROOT).as_posix()
        for path in markdown_files(REPO_ROOT)
        if not OWNER_RE.search(authored_text(path, REPO_ROOT))
    ]
    assert without_owner == [f"{TEAM_DIR}/{F_AUDITREPORT}"]


def test_only_one_document_folds_owner_and_related_onto_one_line():
    """A tolerated deviation, pinned: it may not spread to a second document."""
    folded = [
        path.relative_to(REPO_ROOT).as_posix()
        for path in markdown_files(REPO_ROOT)
        if combined_preamble_lines(path, REPO_ROOT)
    ]
    assert folded == [f"{TEAM_DIR}/Pi-Packaging.md"]


def test_every_team_document_named_by_the_config_exists():
    missing = [name for name in DOCS if not (REPO_ROOT / TEAM_DIR / name).is_file()]
    assert missing == []


def test_each_owner_line_names_the_role_the_config_assigns():
    """A document owned by the wrong role is a document nobody maintains."""
    for name, owner in DOCS.items():
        text = (REPO_ROOT / TEAM_DIR / name).read_text(encoding="utf-8")
        match = OWNER_RE.search(preamble(text))
        assert match, f"{TEAM_DIR}/{name} has no Owner: line"
        stated = re.sub(r"[^a-z0-9]", "", match.group("owner").lower())
        wanted = re.sub(r"[^a-z0-9]", "", owner.lower())
        assert stated.startswith(wanted), (
            f"{TEAM_DIR}/{name}: owner {match.group('owner')!r} != {owner!r}"
        )


def test_the_checks_reach_a_tree_that_is_not_empty():
    """A guard over an empty walk passes vacuously; both sets must be non-trivial."""
    assert len(markdown_files(REPO_ROOT)) >= len(DOCS), "fewer documents than the config names"
    assert len(relative_links(REPO_ROOT)) >= 20, "the link walk found almost no links"


def test_the_design_asset_geometry_matches_the_files():
    """A figure table that disagrees with its file is a stale record.

    Every raster and SVG in ``assets/`` is measured (`viewBox` for SVG, the PNG
    IHDR for raster) and must appear with that exact size in ``Design.md``. A new
    figure without a record, or a record that drifts after a re-export, fails.
    """
    design = (REPO_ROOT / TEAM_DIR / "Design.md").read_text(encoding="utf-8")
    measured = {}
    for path in sorted((REPO_ROOT / "assets").iterdir()):
        rel = f"assets/{path.name}"
        if path.suffix == ".svg":
            match = re.search(r'viewBox="0 0 (\d+) (\d+)"', path.read_text(encoding="utf-8"))
            if match:
                measured[rel] = (int(match.group(1)), int(match.group(2)))
        elif path.suffix == ".png":
            data = path.read_bytes()
            if data[:8] == b"\x89PNG\r\n\x1a\n":
                measured[rel] = struct.unpack(">II", data[16:24])
    assert measured, "no measurable asset found under assets/"
    for rel, expected in measured.items():
        rows = [line for line in design.splitlines() if f"`{rel}`" in line]
        assert rows, f"{rel} is not recorded in Design.md"
        recorded = set()
        for line in rows:
            for cell in (part.strip() for part in line.strip().strip("|").split("|")):
                match = re.fullmatch(r"(\d+)\s*[x×]\s*(\d+)", cell)
                if match:
                    recorded.add((int(match.group(1)), int(match.group(2))))
        assert recorded == {expected}, (rel, expected, sorted(recorded))


