"""Documentation hygiene: one H1, an owner, a related-links line, live links.

Why this exists: the writing standard in `templates/AGENTS.md` is a hard rule, but
nothing enforced it. A document can lose its `Owner:` line, grow a second `# H1`,
or keep a link to a file that was renamed, and the only detector was a reviewer
reading 20 files by hand. `teamwork links` catches broken link *targets*; it does
not catch a missing owner or a duplicated title, and it runs only in CI.

The walk is over the tree (`docs/**/*.md`), never a hard-coded list, so a new
document is covered the day it lands. Two facts about this tree shape the test,
both measured rather than assumed:

* `docs/Team/AuditManifest.md` is generated by `teamwork ledger export`
  (`config.F_AUDITREPORT`), so it carries no owner block. The exemption names that
  one file, and a test asserts it is still the *only* document without an owner,
  so the exemption cannot quietly spread.
* `docs/Team/Pi-Packaging.md` puts `Owner:` and `Related:` on one physical line
  ("Owner: CEO. Related: [Plan](Plan.md) ..."), which is a deviation from the
  template's two separate lines. The check tolerates the combined form - both
  markers must still be present with a value - and a second test pins the deviation
  to that single document, so it cannot become the house style. This is a finding
  for the document's owner, not something this test can silently fix.

Link checking reuses the engine's own reader (`strip_code`,
`strip_quoted_evidence`, `_link_targets`, `_resolve`), so a link this test reports
is a link `teamwork links` also reports, and a fenced example or a quoted Archive
entry is skipped for the same reason it is skipped there.

Mutations run against a `tmp_path` copy of `docs/` plus what its links reach
outside it - the `references/` directory and the root-level files named in
`ROOT_LINK_FILES` - so the real tree is never written.
"""

from __future__ import annotations

import re
import shutil
import struct
from pathlib import Path

import pytest

from teamwork import engine
from teamwork.config import DOCS, F_AUDITREPORT

REPO_ROOT = Path(__file__).resolve().parents[2]
DOCS_DIR = "docs"
TEAM_DIR = "docs/Team"

#: Directories outside `docs/` that documents link into. Measured.
EXTRA_TREES = ("references",)

#: Root-level files outside `docs/` that documents link to. A document may cite a
#: top-level file (a CHANGELOG, a README); the copy must carry it or the link check
#: reports a broken link that only the missing copy caused. Measured by resolving
#: every relative link in `docs/` against the repository root; extend the list when
#: a document starts linking to another root-level file.
ROOT_LINK_FILES = ("CHANGELOG.md", "README.md", "CONTRIBUTING.md")

OWNER_RE = re.compile(r"(?<![\w`])Owner:\s*(?P<owner>[^.,;\n]*)")
RELATED_RE = re.compile(r"(?<![\w`])Related:\s*(?P<targets>[^\n]*)")
H1_RE = re.compile(r"^# \S", re.M)
SECTION_RE = re.compile(r"^## ", re.M)


def generated_documents() -> set[str]:
    """Documents the engine writes itself; they carry no owner block."""
    return {F_AUDITREPORT}


def markdown_files(root: Path) -> list[Path]:
    """Committed prose: the team documents and the skill's references."""
    paths = list((root / DOCS_DIR).rglob("*.md"))
    paths += list((root / "references").rglob("*.md"))
    return sorted(path for path in paths if path.is_file())


def authored_text(path: Path, root: Path) -> str:
    """The text a human maintains: no code fences, no quoted Archive evidence."""
    rel = path.relative_to(root).as_posix()
    raw = path.read_text(encoding="utf-8", errors="replace")
    return engine.strip_code(engine.strip_quoted_evidence(rel, raw))


def preamble(text: str) -> str:
    """The front matter between the H1 and the first `##` section."""
    match = SECTION_RE.search(text)
    return text[: match.start()] if match else text


def preamble_problems(rel: str, text: str) -> list[str]:
    """One title, one owner, one related line, all in the front matter."""
    problems: list[str] = []
    titles = H1_RE.findall(text)
    if len(titles) != 1:
        problems.append(f"{rel}: {len(titles)} level-1 heading(s), want exactly 1")
    front = preamble(text)
    owner = OWNER_RE.search(front)
    if not owner or not owner.group("owner").strip():
        problems.append(f"{rel}: no `Owner:` line")
    related = RELATED_RE.search(front)
    if not related or not related.group("targets").strip():
        problems.append(f"{rel}: no `Related:` line")
    return problems


def combined_preamble_lines(path: Path, root: Path) -> bool:
    """`Owner:` and `Related:` share one physical line (the tolerated deviation)."""
    for line in preamble(authored_text(path, root)).splitlines():
        if OWNER_RE.search(line) and RELATED_RE.search(line):
            return True
    return False


def structure_problems(root: Path) -> list[str]:
    """Every hygiene violation under `root/docs`."""
    problems: list[str] = []
    generated = generated_documents()
    for path in markdown_files(root):
        if path.name in generated:
            continue
        rel = path.relative_to(root).as_posix()
        problems.extend(preamble_problems(rel, authored_text(path, root)))
    return problems


def link_problems(root: Path) -> list[str]:
    """Relative markdown links that do not resolve to a file in the tree."""
    problems: list[str] = []
    for path in markdown_files(root):
        rel = path.relative_to(root).as_posix()
        for label, target in engine._link_targets(path, rel):
            if (
                target.startswith("#")
                or "://" in target
                or target.startswith(engine.EXTERNAL_SCHEMES)
            ):
                continue
            if not engine._resolve(path, target).exists():
                problems.append(f"{rel}: [{label}]({target}) does not resolve")
    return problems


def relative_links(root: Path) -> list[tuple[str, str]]:
    out = []
    for path in markdown_files(root):
        rel = path.relative_to(root).as_posix()
        for _label, target in engine._link_targets(path, rel):
            if (
                target.startswith("#")
                or "://" in target
                or target.startswith(engine.EXTERNAL_SCHEMES)
            ):
                continue
            out.append((rel, target))
    return out


@pytest.fixture
def docs_copy(tmp_path: Path) -> Path:
    """A throwaway repository root holding the documented tree."""
    shutil.copytree(REPO_ROOT / DOCS_DIR, tmp_path / DOCS_DIR)
    for extra in EXTRA_TREES:
        shutil.copytree(REPO_ROOT / extra, tmp_path / extra)
    for name in ROOT_LINK_FILES:
        shutil.copy2(REPO_ROOT / name, tmp_path / name)
    return tmp_path


