"""The roster tier is a supported recipe, and a slim tier must not weaken a gate.

Every extra role costs a charter copy, a shared queue, two memory files and the
startup read, so the default roster is deliberately small. These tests pin that
the small roster still closes the gates it claims to close: the tribunal keeps a
neutral seat, the optional layers are not reported as gaps, and the required roles
are never silently missing.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from teamwork import engine


def team_root(project: Path) -> Path:
    return (
        project / engine.TEAM_ROOT_DIR / engine.TEAMS_SUBDIR / engine.team_slug(project)
    ).resolve()


def test_slim_is_the_default_roster(cli, project: Path) -> None:
    assert cli("--project", project, "init", "--no-git") == 0
    root = team_root(project)
    roles = engine.list_roles(root)
    assert engine.DEFAULT_ROSTER_TIER == "slim"
    assert sorted(roles) == sorted(engine.ROSTER_TIERS["slim"])
    # Two reviewers: one verifies, a different one merges.
    assert len(engine.instances_of(root, "reviewer")) == 2


@pytest.mark.parametrize("tier", ["slim", "standard", "full"])
def test_every_tier_staffs_the_required_gates(cli, project: Path, tier: str) -> None:
    assert cli("--project", project, "init", "--roster", tier, "--no-git") == 0
    root = team_root(project)
    roles = set(engine.list_roles(root))
    for required in engine.ROSTER_REQUIRED:
        assert required in roles, f"{tier} drops {required}"
    assert len(engine.required_tribunal(root)) >= engine.TRIBUNAL_MIN_SIGNERS


def test_a_slim_tier_reports_folded_lanes_and_no_phantom_layer_gaps(
    cli, project: Path, capsys
) -> None:
    capsys.readouterr()
    assert cli("--project", project, "init", "--roster", "slim", "--no-git") == 0
    out = capsys.readouterr().out
    assert "roster slim" in out
    assert "folded lanes" in out
    assert "product-manager" in out

    root = team_root(project)
    assert engine.staffed_layers(root) == ["goal", "system", "unit", "integration", "acceptance"]
    # An unstaffed role cannot be asked for a layer it has no one to run.
    assert engine.instances_of(root, "designer") == []
    assert "ui" not in engine.staffed_layers(root)


def test_explicit_agents_still_win_over_the_tier(cli, project: Path) -> None:
    assert cli("--project", project, "init", "--agents", "ceo,developer-1", "--no-git") == 0
    root = team_root(project)
    assert engine.list_roles(root) == ["ceo", "developer"]


def test_a_roster_missing_a_gate_says_so(cli, project: Path, capsys) -> None:
    capsys.readouterr()
    assert cli("--project", project, "init", "--agents", "ceo,developer-1", "--no-git") == 0
    out = capsys.readouterr().out
    assert "WARNING the roster has no 'tester'" in out, out


def _size(path: Path) -> int:
    """Content size independent of the checkout's line endings.

    A Windows checkout rewrites LF to CRLF, so a raw ``stat().st_size`` measures a
    bigger file there and the documented tier cost would look wrong on one
    platform only.
    """
    return len(path.read_bytes().replace(b"\r\n", b"\n"))


def test_documented_tier_costs_match_the_measured_ones(repo_root) -> None:
    """The size table in SKILL.md and references/Roles.md is generated by hand.

    A roster that grows or a charter that is edited moves the number, so the doc
    quotes it per instance and this test keeps the two in step.
    """
    charters = {p.stem: _size(p) for p in (repo_root / "roles").glob("*.md")}
    agents_md = _size(repo_root / "templates" / "AGENTS.md")
    for name in ("SKILL.md", "references/Roles.md"):
        text = (repo_root / name).read_text(encoding="utf-8")
        for tier in ("slim", "standard", "full"):
            roster = engine.expand_roster(tier)
            cost = sum(agents_md + charters[engine.resolve_role(i)] for i in roster["instances"])
            row = f"| `{tier}`"
            assert row in text or f"`{tier}` (default)" in text, (name, tier)
            assert f"{round(cost / 1000)} kB" in text, (name, tier, cost)
