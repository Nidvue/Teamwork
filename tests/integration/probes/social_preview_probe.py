#!/usr/bin/env python3
"""Integration probe (area social-preview): the committed card is reproducible.

`assets/social-preview.png` is a raster with no third-party source. The only
replayable source of a raster is a generator committed in the same revision: run
it and compare the bytes it writes with the bytes git ships. A renderer that
exists only in an agent's local Scratch directory is not part of the revision, so
a clone cannot reproduce the card and the card is not replayable.

Exit 0: the committed bytes were regenerated byte-for-byte by a committed script.
Exit 1: they were not, and the reason is printed.
"""

from __future__ import annotations

import argparse
import hashlib
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

CARD = "assets/social-preview.png"
# An image-composition import, not a mention: the probe itself names the card and
# the libraries, and a test never generates a shipped asset.
GENERATOR_HINTS = ("import cairosvg", "from PIL", "import PIL", "ImageDraw")
EXPECTED_CHUNKS = ["IHDR", "IDAT", "IDAT", "IEND"]


def png_facts(data: bytes) -> tuple[int, int, int, list[str], int]:
    """Width, height, colour type, chunk types and metadata-chunk count."""
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit("not a PNG: bad signature")
    width, height, depth, colour = struct.unpack(">IIBB", data[16:26])
    chunks: list[str] = []
    metadata = 0
    pos = 8
    while pos + 8 <= len(data):
        (length,) = struct.unpack(">I", data[pos : pos + 4])
        kind = data[pos + 4 : pos + 8].decode("ascii", "replace")
        chunks.append(kind)
        if kind not in ("IHDR", "IDAT", "IEND"):
            metadata += 1
        pos += 12 + length
    if depth != 8:
        raise SystemExit(f"unexpected bit depth {depth}")
    return width, height, colour, chunks, metadata


def git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, text=True, check=False
    )


def git_root(repo: Path, override: str | None) -> Path | None:
    """A checkout git can read.

    A linked worktree's `.git` file holds a Windows path, so git inside WSL cannot
    follow it; the parent checkout can, and `--git-rev` then names the revision
    whose file list is authoritative.
    """
    if override:
        return Path(override)
    if git(repo, "rev-parse", "--git-dir").returncode == 0:
        return repo
    for base in repo.parents:
        if (base / ".git").is_dir() and git(base, "rev-parse", "--git-dir").returncode == 0:
            return base
    return None


def committed_generators(repo: Path, root: Path | None, rev: str) -> list[str]:
    """Tracked Python files that compose this exact raster."""
    if root is None:
        print("git unavailable: scanning the working tree for a generator instead")
        candidates = [
            str(path.relative_to(repo)).replace("\\", "/")
            for path in repo.rglob("*.py")
            if not any(part in (".git", ".pi", ".venv", "venv", "site") for part in path.parts)
        ]
    else:
        listed = git(root, "ls-tree", "-r", "--name-only", rev)
        if listed.returncode != 0:
            raise SystemExit(f"git ls-tree {rev} failed: {listed.stderr.strip()}")
        candidates = [rel for rel in listed.stdout.splitlines() if rel.endswith(".py")]
    found = []
    for rel in candidates:
        if rel.startswith(("tests/", "docs/", "references/")):
            continue
        path = repo / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if any(hint in text for hint in GENERATOR_HINTS):
            found.append(rel)
    return found


def image_python(repo: Path, override: str | None) -> str:
    """An interpreter that can run the generator (cairosvg + Pillow)."""
    candidates = [override] if override else []
    candidates.append(sys.executable)
    for base in (repo, *repo.parents):
        candidates.append(str(base / ".venv" / "bin" / "python"))
    for candidate in candidates:
        if not candidate or not Path(candidate).exists():
            continue
        probe = subprocess.run(
            [candidate, "-c", "import cairosvg, PIL"],
            capture_output=True,
            text=True,
            check=False,
        )
        if probe.returncode == 0:
            return candidate
    return ""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", default=".", help="repository root (default: cwd)")
    ap.add_argument(
        "--python",
        default=None,
        help="interpreter for the generator (default: the first that imports cairosvg + PIL)",
    )
    ap.add_argument(
        "--git-root",
        default=None,
        help="checkout git can read (default: --repo, else the nearest parent checkout)",
    )
    ap.add_argument(
        "--git-rev",
        default="HEAD",
        help="revision whose tracked file list defines a committed generator (default: HEAD)",
    )
    args = ap.parse_args(argv)

    repo = Path(args.repo).resolve()
    root = git_root(repo, args.git_root)
    print(f"git root: {root or 'none'} at {args.git_rev}")
    card = repo / CARD
    if not card.is_file():
        print(f"FAIL {CARD} is not in the tree at {repo}")
        return 1
    data = card.read_bytes()
    width, height, colour, chunks, metadata = png_facts(data)
    digest = hashlib.sha256(data).hexdigest()
    print(f"card: {CARD} {len(data)} B sha256 {digest}")
    print(f"png: {width}x{height} depth 8 colourtype {colour} chunks {'/'.join(chunks)}")
    print(f"metadata chunks: {metadata}")

    problems = []
    if (width, height) != (1280, 640):
        problems.append(f"size {width}x{height} != 1280x640")
    if colour != 2:
        problems.append(f"colour type {colour} != 2 (RGB)")
    if chunks != EXPECTED_CHUNKS:
        problems.append(f"chunks {'/'.join(chunks)} != {'/'.join(EXPECTED_CHUNKS)}")
    if metadata:
        problems.append(f"{metadata} metadata chunk(s), expected 0")

    generators = committed_generators(repo, root, args.git_rev)
    print(f"committed generators: {generators or 'none'}")
    if not generators:
        if root is not None:
            listed = git(root, "ls-tree", "-r", "--name-only", args.git_rev)
            naming = [rel for rel in listed.stdout.splitlines() if rel.endswith(".py")]
            print(f"tracked python files at {args.git_rev}: {len(naming)}")
        problems.append("no committed generator: the card cannot be rebuilt from a clone")
    else:
        python = image_python(repo, args.python)
        print(f"generator interpreter: {python or 'none with cairosvg + Pillow'}")
        if not python:
            problems.append(
                f"cannot run {generators[0]}: no interpreter here imports cairosvg and PIL"
                " (the repo .venv has both; the Windows venv does not)"
            )
            generators = []
    if generators:
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "card.png"
            run = subprocess.run(
                [python, generators[0], "--output", str(out)],
                cwd=str(repo),
                capture_output=True,
                text=True,
                check=False,
            )
            if run.returncode != 0:
                tail = (run.stderr or run.stdout).strip().splitlines()[-3:]
                problems.append(f"generator exit {run.returncode}: {' | '.join(tail)}")
            elif not out.is_file():
                problems.append(f"generator wrote no file at {out}")
            else:
                regen = out.read_bytes()
                regen_digest = hashlib.sha256(regen).hexdigest()
                print(f"regenerated: {len(regen)} B sha256 {regen_digest}")
                if regen_digest != digest:
                    problems.append(
                        f"regenerated sha256 {regen_digest[:16]} != committed {digest[:16]}"
                    )

    if problems:
        for problem in problems:
            print(f"FAIL {problem}")
        print(f"RESULT FAIL social-preview: {len(problems)} problem(s) at {digest[:16]}")
        return 1
    print(f"RESULT PASS social-preview: {CARD} regenerated byte-for-byte ({digest})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
